"""Generate web/public/runtime/python/turtle.py from CPython's turtle.py (D29).

Pyodide has no tkinter and no turtle. We ship the standard library's module
(so the whole API and its behavior are the real ones) with its Tkinter
interface replaced by _terrarium_turtle.py:

- the tkinter imports go,
- ScrolledCanvas, _Root, Canvas and TurtleScreenBase (the block that ends at
  "End of Tkinter - interface") come from _terrarium_turtle instead.

Run with the Python minor version Pyodide uses:

    uv run --python 3.14 scripts/make-turtle.py
"""

import pathlib
import sys
import sysconfig

source_path = pathlib.Path(sysconfig.get_paths()["stdlib"]) / "turtle.py"
source = source_path.read_text()
out = pathlib.Path(__file__).resolve().parent.parent / "web/public/runtime/python/turtle.py"


def replace_once(text, old, new):
    if text.count(old) != 1:
        sys.exit(f"expected exactly one {old!r} in {source_path}")
    return text.replace(old, new)


text = replace_once(source, "import tkinter as TK\n", "")
text = replace_once(text, "from tkinter import simpledialog\n", "")

start = text.index("class ScrolledCanvas(TK.Frame):")
end_marker = "###                  End of Tkinter - interface"
end = text.index("\n", text.index("#" * 20, text.index(end_marker))) + 1
backend = (
    "# terrarium: the Tkinter interface is replaced by the browser backend (D29).\n"
    "from _terrarium_turtle import TK, Canvas, ScrolledCanvas, _Root, TurtleScreenBase\n"
)
text = text[:start] + backend + text[end:]

header = (
    f"# Generated by app/scripts/make-turtle.py from CPython {sys.version.split()[0]}'s turtle.py.\n"
    "# Do not edit: change _terrarium_turtle.py or the script.\n"
)
out.write_text(header + text)
print(f"wrote {out} ({len(text.splitlines())} lines) from {source_path}")
